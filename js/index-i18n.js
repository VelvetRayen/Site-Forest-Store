let currentLang = localStorage.getItem('app_lang') || 'en';

function setLanguage(lang) {
  currentLang = lang;
  localStorage.setItem('app_lang', lang);

  const isAr = lang === 'ar';
  document.documentElement.lang = lang;
  document.documentElement.dir = isAr ? 'rtl' : 'ltr';

  const langText = document.getElementById('lang-text');
  const langTextMobile = document.getElementById('lang-text-mobile');
  if (langText) langText.textContent = isAr ? 'EN' : 'AR';
  if (langTextMobile) langTextMobile.textContent = isAr ? 'EN' : 'AR';

  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (translations[lang][key]) {
      el.textContent = translations[lang][key];
    }
  });

  document.querySelectorAll('[data-i18n-ph]').forEach(el => {
    const key = el.getAttribute('data-i18n-ph');
    if (translations[lang][key]) {
      el.placeholder = translations[lang][key];
    }
  });

  const featuresGrid = document.getElementById('features-grid');
  if (featuresGrid) {
    featuresGrid.innerHTML = translations[lang].features.map(f => `
      <div class="card-hover" style="background:rgba(255,255,255,.03); border:1px solid rgba(255,255,255,.06); border-radius:16px; padding:24px;">
        <div class="icon-box" style="margin-bottom:16px;"><i data-lucide="${f.icon}" style="width:24px;height:24px;"></i></div>
        <h3 style="color:#fff; font-weight:700; font-size:18px; margin:0 0 8px;">${f.title}</h3>
        <p style="color:#6b7280; font-size:14px; line-height:1.7; margin:0;">${f.desc}</p>
      </div>
    `).join('');
  }

  const servicesGrid = document.getElementById('services-grid');
  if (servicesGrid) {
    servicesGrid.innerHTML = translations[lang].services.map(s => `
      <div class="card-hover" style="position:relative; background:rgba(255,255,255,.02); border:1px solid rgba(255,255,255,.08); border-radius:20px; padding:28px; overflow:hidden;">
        ${s.badge ? `<span style="position:absolute; top:20px; ${isAr ? 'left:20px;' : 'right:20px;'} background:rgba(0,255,82,.12); border:1px solid rgba(0,255,82,.3); color:var(--green-a); font-size:11px; font-weight:800; padding:4px 12px; border-radius:9999px; text-transform:uppercase; letter-spacing:0.05em; box-shadow: 0 0 10px rgba(0,255,82,0.2);">${s.badge}</span>` : ''}
        <div style="width:52px; height:52px; border-radius:14px; background:linear-gradient(135deg, rgba(38,239,0,.2), rgba(21,128,61,.1)); border:1px solid rgba(0,255,82,.3); display:flex; align-items:center; justify-content:center; color:var(--green-a); margin-bottom:20px; box-shadow: 0 0 15px rgba(0,255,82,0.15);">
          <i data-lucide="${s.icon}" style="width:26px;height:26px;"></i>
        </div>
        <h3 style="color:#fff; font-weight:800; font-size:20px; margin:0 0 8px 0; letter-spacing:-0.02em;">${s.title}</h3>
        <p style="color:#9ca3af; font-size:14px; line-height:1.6; margin:0;">${s.desc}</p>
      </div>
    `).join('');
  }

  const stepsGrid = document.getElementById('steps-grid');
  if (stepsGrid) {
    stepsGrid.innerHTML = translations[lang].steps.map(s => `
      <div class="card-hover" style="position:relative; background:rgba(255,255,255,.03); border:1px solid rgba(0,255,82,.15); border-radius:20px; padding:28px; overflow:hidden; display:flex; flex-direction:column; justify-content:space-between; transition:all 0.3s ease;">
        ${s.badge ? `<span style="position:absolute; top:18px; ${isAr ? 'left:18px;' : 'right:18px;'} background:rgba(0,255,82,.1); border:1px solid rgba(0,255,82,.3); color:var(--green-a); font-size:10px; font-weight:800; padding:4px 10px; border-radius:9999px; text-transform:uppercase; letter-spacing:0.05em;">${s.badge}</span>` : ''}
        <div>
          <div style="width:60px; height:60px; border-radius:16px; background:rgba(10, 13, 10, 0.8); border:1px solid rgba(0,255,82,.3); display:flex; align-items:center; justify-content:center; padding:10px; margin-bottom:20px; box-shadow: 0 0 15px rgba(0,255,82,0.15);">
            <img src="${s.logo}" alt="${s.title}" style="max-width:100%; max-height:100%; object-fit:contain;" onerror="this.onerror=null; this.src='https://cdn-icons-png.flaticon.com/512/893/893081.png';" />
          </div>
          <h3 style="color:#fff; font-weight:800; font-size:20px; margin:0 0 8px 0; letter-spacing:-0.02em;">${s.title}</h3>
          <p style="color:#9ca3af; font-size:13px; line-height:1.6; margin:0;">${s.desc}</p>
        </div>
        <div style="margin-top:20px; display:flex; align-items:center; gap:6px; color:var(--green-a); font-size:12px; font-weight:700;">
          <i data-lucide="shield-check" style="width:14px; height:14px;"></i>
          <span>${isAr ? 'بوابة مشفرة وموثوقة' : 'Verified Gateway'}</span>
        </div>
      </div>
    `).join('');
  }

  if (window.lucide) lucide.createIcons();
}

document.getElementById('lang-toggle-btn').addEventListener('click', () => {
  setLanguage(currentLang === 'en' ? 'ar' : 'en');
});
document.getElementById('lang-toggle-btn-mobile').addEventListener('click', () => {
  setLanguage(currentLang === 'en' ? 'ar' : 'en');
});
